static uint32_t s_refusals;

bool ml_tls_spki_distrusted(const uint8_t *spki_der, size_t len)
{
    if (!spki_der || !len) return false;
    uint8_t digest[32];
    if (mbedtls_sha256(spki_der, len, digest, 0) != 0) return true;   /* fail closed */
    for (unsigned i = 0; i < ML_TLS_DISTRUSTED_COUNT; i++) {
        if (!memcmp(digest, s_distrusted[i], sizeof digest)) return true;
    }
    return false;
}

uint32_t ml_tls_distrust_refusals(void)
{
    return __atomic_load_n(&s_refusals, __ATOMIC_RELAXED);
}

/* The bundle's own callback (the same function for every configuration). */
static int (*s_bundle_verify)(void *, mbedtls_x509_crt *, int, uint32_t *);

/* Called by mbedTLS for every certificate of the chain, top first. The flag
 * is added after the bundle callback, which may clear the flags of the
 * certificate it anchors, so it cannot be cleared again. */
static int distrust_verify(void *ctx, mbedtls_x509_crt *crt, int depth, uint32_t *flags)
{
    int ret = s_bundle_verify ? s_bundle_verify(ctx, crt, depth, flags) : 0;
    if (crt && ml_tls_spki_distrusted(crt->pk_raw.p, crt->pk_raw.len)) {
        *flags |= MBEDTLS_X509_BADCERT_NOT_TRUSTED;
        __atomic_fetch_add(&s_refusals, 1, __ATOMIC_RELAXED);
#ifndef ML_TLS_HOST_TEST
        ESP_LOGE(TAG, "TLS chain refused: certificate at depth %d has a compromised CA key", depth);
#endif
    }
    return ret;
}

